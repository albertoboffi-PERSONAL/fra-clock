from model import T, V
def amp(dy, U, J):
    """U102 layout at dy=0; U101 at dy=-211."""
    def P(pts): return [(x, y + dy) for x, y in pts]
    it = []
    p5, g = "+5V", "GND"
    op, on = "Net-(%s-Pin_1)" % J, "Net-(%s-Pin_2)" % J
    # C72 -> C102 -> pins 8/7
    it += T("F.Cu", p5, 0.5, P([(172.5, 239.94), (172.5, 241.0), (172.06, 241.44), (172.06, 241.69)]), U + "_c72_c102")
    it += T("F.Cu", p5, 0.25, P([(172.06, 241.69), (172.06, 243.25)]), U + "_vdd8")
    it += T("F.Cu", p5, 0.25, P([(172.06, 242.45), (172.56, 242.45), (172.56, 243.25)]), U + "_vdd7")
    # GND pins -> EP, EP vias
    it += T("F.Cu", g, 0.25, P([(171.38, 244.94), (172.3, 244.94)]), U + "_g11")
    it += T("F.Cu", g, 0.25, P([(174.25, 244.44), (173.3, 244.44)]), U + "_g3")
    it += T("F.Cu", g, 0.25, P([(173.06, 246.12), (173.06, 245.2)]), U + "_g15")
    it += [V(g, 172.5025, 244.3775 + dy, tag=U + "_ep_v1"), V(g, 173.1225, 244.9975 + dy, tag=U + "_ep_v2")]
    # speaker outputs: OUTP -> pin1 (from below), OUTN -> pin2 (around west side)
    it += T("F.Cu", op, 0.25, P([(171.38, 243.94), (170.75, 243.94), (170.45, 243.64)]), U + "_outp_esc")
    it += T("F.Cu", op, 0.5, P([(170.45, 243.64), (165.33, 243.64), (165.2, 243.51), (165.2, 235.6), (165.8, 235.0), (165.8, 234.52)]), U + "_outp")
    it += T("F.Cu", on, 0.25, P([(171.38, 244.44), (170.2, 244.44)]), U + "_outn_esc")
    it += T("F.Cu", on, 0.5, P([(170.2, 244.44), (165.0, 244.44), (164.4, 243.84), (164.4, 233.12), (165.0, 232.52), (167.07, 232.52)]), U + "_outn")
    return it
def items():
    return amp(0.0, "U102", "J102") + amp(-211.0, "U101", "J101")
